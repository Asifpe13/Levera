#!/usr/bin/env node
/**
 * Cross-platform (Windows/macOS/Linux) setup for phone development.
 * Detects the computer's LAN IP and writes env files for Expo + web.
 *
 * Usage:  node scripts/setup-phone-dev.mjs
 *         node scripts/setup-phone-dev.mjs 192.168.1.42   (manual IP override)
 */
import { networkInterfaces } from 'os'
import { writeFileSync, existsSync, copyFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')

function detectLanIp() {
  const nets = networkInterfaces()
  const candidates = []
  for (const [name, addrs] of Object.entries(nets)) {
    for (const addr of addrs || []) {
      if (addr.family !== 'IPv4' || addr.internal) continue
      // Prefer typical home-router ranges over Docker/WSL/VPN adapters
      const score =
        addr.address.startsWith('192.168.') ? 3 :
        addr.address.startsWith('10.') ? 2 :
        addr.address.startsWith('172.') ? 1 : 0
      candidates.push({ ip: addr.address, name, score })
    }
  }
  candidates.sort((a, b) => b.score - a.score)
  return candidates[0] || null
}

const manualIp = process.argv[2]
const detected = detectLanIp()
const lanIp = manualIp || detected?.ip

if (!lanIp) {
  console.error('❌ לא נמצא IP ברשת. הרץ עם IP ידני:')
  console.error('   node scripts/setup-phone-dev.mjs 192.168.1.42')
  process.exit(1)
}

const apiUrl = `http://${lanIp}:8000`
const webUrl = `http://${lanIp}:5173`

if (!existsSync(join(ROOT, '.env')) && existsSync(join(ROOT, '.env.example'))) {
  copyFileSync(join(ROOT, '.env.example'), join(ROOT, '.env'))
  console.log('✓ נוצר .env מהדוגמה')
}

writeFileSync(
  join(ROOT, 'mobile', '.env'),
  `# Auto-generated by setup-phone-dev.mjs — IP: ${lanIp}\nEXPO_PUBLIC_API_URL=${apiUrl}\n`,
)

writeFileSync(
  join(ROOT, 'frontend', '.env.local'),
  `# Auto-generated — for npm run dev:phone\nVITE_API_URL=${apiUrl}\n`,
)

console.log('')
console.log('=== Levera — מוכן לטלפון ===')
console.log('')
console.log(`  IP ברשת:     ${lanIp}${detected && !manualIp ? `  (מתאם: ${detected.name})` : ''}`)
console.log(`  Backend:     ${apiUrl}`)
console.log(`  Web (PWA):   ${webUrl}`)
console.log('')
console.log('  mobile/.env ו-frontend/.env.local עודכנו.')
console.log('')
console.log('הרץ בטרמינלים נפרדים:')
console.log('')
console.log('  # 1 — MongoDB (Docker) או MONGODB_URI של Atlas ב-.env')
console.log('  docker compose up -d')
console.log('')
console.log('  # 2 — Backend')
console.log('  cd backend')
console.log('  pip install -r requirements.txt')
console.log('  python run_api.py')
console.log('')
console.log('  # 3 — Expo (React Native)')
console.log('  cd mobile')
console.log('  npm install')
console.log('  npm start')
console.log('')
console.log('  # 4 — Web/PWA (אופציונלי)')
console.log('  cd frontend && npm install && npm run dev:phone')
console.log('')
console.log(`בדיקה מדפדפן הטלפון: ${apiUrl}/health`)
console.log('Expo Go: סרוק את ה-QR — טלפון ומחשב על אותה Wi-Fi!')
console.log('')
if (!manualIp) {
  console.log('IP שגוי? הרץ עם IP ידני: node scripts/setup-phone-dev.mjs 192.168.x.x')
}
